def reference_material(κ, μ, dim, operation):
    if operation == "arithmetic":
        κ0 = 0.5 * (np.max(κ) + np.min(κ))
        μ0 = 0.5 * (np.max(μ) + np.min(μ))
    elif operation == "geometric":
        κ0 = np.sqrt(np.max(κ) * np.min(κ))
        μ0 = np.sqrt(np.max(μ) * np.min(μ))
    elif operation == "maximum":
        α = 1.0 + 1.0e-2
        κ0 = np.max(κ) * α
        μ0 = np.max(μ) * α
    elif operation == "minimum":
        α = 1.0 - 1.0e-2
        κ0 = np.min(κ) * α
        μ0 = np.min(μ) * α
    else:
        raise ValueError(f"Invalid operation: {operation}")
    ν0 = material.poisson_from_bulk_and_shear_moduli(κ0, μ0, dim)
    return material.create(μ0, ν0, dim)

def operatorB(φ, biot):
    blocks = []
    if φ.ndim == 2:
        for i in range(φ.shape[0]):
            for j in range(φ.shape[0]):  # Use φ.shape[1] for 2D iteration
                b_ = biot[φ[i, j]]
                block = np.array([b_, b_, 0])  # 3 values for the block
                blocks.append(block)
    elif φ.ndim == 3:
        for i in range(φ.shape[0]):
            for j in range(φ.shape[0]):  
                for l in range(φ.shape[0]):  
                    b_ = (1-φ[i, j, l])*biot[0] + φ[i, j, l]*biot[1]
                    block = np.array([b_, b_, b_, 0, 0, 0])  # 3 values for the block
                    blocks.append(block)
        

    # Concatenate the blocks to form the final 1D array
    b_t = np.concatenate(blocks, axis=None)

    return b_t

