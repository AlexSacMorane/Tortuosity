def Identity(φ, biot):
    blocks = []
    for i in range(φ.shape[0]):
        for j in range(φ.shape[0]):
            b_ = biot[φ[i, j]]
            block = np.array([b_/b_, b_/b_, 0])
            blocks.append(block)

    b_t = np.concatenate(blocks, axis=None)

    return b_t

