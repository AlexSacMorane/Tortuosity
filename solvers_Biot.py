def adaptive_eyre_milton(
     φ, biot, κ, μ, ν, p_macro,N, alpha, T_macro, Heat_cap,
    alpha_phi,ε_macro,e, green_op_name="willot2015", mu0=None, **kwargs,
):
    """
    Adaptive Eyre-Milton scheme & more

    """
    dim = φ.ndim

    # ----- Reference material -----

    ν0 = ν[1]  # reference material is set to matrix
    μ0 = μ[1]

    # ----- Sollicitation -----
    p0 = p_macro[0] 
    t0 = T_macro[0]

    
    if mu0 is not None:
        μ0 = mu0

    def alpha_tensor(C0, κ, μ, φ):
        ak = 2 * C0.k / (κ + C0.k)
        ak[μ == np.inf] = 0
        ag = 2 * C0.g / (μ + C0.g)
        ag[μ == np.inf] = 0
        α = local_operator(φ, ak, ag)
        return α

    C0 = material.create(μ[0], ν[0], dim)
    # S0 = material.create(
    #     1 / (C0.g * 4),
    #     material.poisson_from_bulk_and_shear_moduli(
    #         1 / (C0.k * dim**2), 1 / (C0.g * 4), dim
    #     ),
    #     dim,
    # )
    Cmatrix = material.create(μ[0], ν[0], dim)

    Γ0 = green_operator(C0, φ.shape, green_op_name=kwargs.get("green_operator", green_op_name))
    α = alpha_tensor(C0, κ, μ, φ)

    κ_D = 2 * κ * C0.k / (κ + C0.k)
    μ_D = 2 * μ * C0.g / (μ + C0.g)
    κ_D[μ == np.inf] = 2 * C0.k
    μ_D[μ == np.inf] = 2 * C0.g
    κ_S = 2 * C0.k**2 / (κ + C0.k)
    μ_S = 2 * C0.g**2 / (μ + C0.g)
    κ_S[μ == np.inf] = 0
    μ_S[μ == np.inf] = 0


    biot_0 = (0.5 * (np.max(biot) + np.min(biot)))
    B = operatorB(φ, biot)
    B2 = operatorB2(φ, biot)
    A = operatorA(φ, alpha)
    B2 = operatorB2(φ, biot)
    
    C_D = local_operator(φ, φ.ndim * κ_D, 2 * μ_D)
    C_SD = local_operator(φ, φ.ndim * (κ_D - κ_S), 2 * (μ_D - μ_S))
    ΔC = local_operator(φ, φ.ndim * (κ - C0.k), 2 * (μ - C0.g))
    vol = np.prod(φ.shape)

    def ref_norm(X):
        X_ = as_grid(X)
        return np.sqrt(np.sum(X_ * C_ε(C0, X_)))

    as_grid = lambda a: np.reshape(a, Γ0.oshape)
    as_vector = lambda a: a.ravel()


    def projections_on_D_S(X):
        XD = Γ0 @ C_ε(C0, as_grid(X)).ravel()
        return XD, X - XD

    def projection_on_D(X):
        return Γ0 @ C_ε(C0, as_grid(X)).ravel()

    # ----- Fields Initialization -----
    C = local_operator(φ, φ.ndim * κ, 2 * μ)
    E_macro = np.zeros(Γ0.oshape)
    E_macro[...] = ε_macro
    E_norm = ref_norm(E_macro)
    E_macro = as_vector(E_macro)
    ε = np.zeros_like(E_macro)
    σ = np.zeros_like(E_macro)
    k = C @ A
    X = E_macro - Γ0 @ (- p0 * B - k * t0)
    C = local_operator(φ, φ.ndim * κ, 2 * μ)

    λ = 0.0
    if kwargs.get("lambda_value", False):  # a given fixed value of lambda
        λ = kwargs.get("lambda_value", False)
    ε_old = np.zeros_like(ε)

    out = []
    sigma = []
    phi = []
    S = []
    i = 0
    first_iteration = True
    while True:

        if (i + 1) % 10 == 0:
            print(f"Adaptive Eyre–Milton, iteration #{i + 1}", flush=True)

        XD, XS = projections_on_D_S(X)

        Z = α @ X + Γ0 @ C_SD @ X 
        X_, Z_ = as_grid(X), as_grid(Z)
        λ = np.sum(X_ * C_ε(C0, Z_)) / np.sum(Z_ * C_ε(C0, Z_))

        if kwargs.get("lambda_value", False):  # a given fixed value of lambda
            λ = kwargs.get("lambda_value", False)

        ε = E_macro - Γ0 @ (ΔC @ ε - p0 * B - k * t0) + λ * α @ X

        phi_phi0 = (B2 @ ε) + N_i(φ, N, p0) - alphaphi_i(φ, alpha_phi) * t0
        S_s = k @ ε - alphaphi_i(φ, alpha_phi) * p0 + heat_i(φ, Heat_cap, t0)


        σ = C @ ε - (p0 * B) - (k * t0) + λ * C_D @ X 
        Delta_D = ref_norm(XS) / ref_norm(C_ε(S0, as_grid(σ)))
        out.append(Delta_D)
        print(Delta_D)
        if φ.ndim == 3:
            row = [
                np.sum(σ[::6])/(len(σ)/6),
                np.sum(σ[1::6])/(len(σ)/6),
                np.sum(σ[2::6])/(len(σ)/6),
                np.sum(σ[3::6])/(len(σ)/6),
                np.sum(σ[4::6])/(len(σ)/6),
                np.sum(σ[5::6])/(len(σ)/6),
            ]
        if φ.ndim == 2:
            row = [
                np.sum(σ[::3])/(len(σ)/3),
                np.sum(σ[1::3])/(len(σ)/3),
                np.sum(σ[2::3])/(len(σ)/3),
            ]

        phi_row = np.sum(phi_phi0)/(len(phi_phi0)),
        S_row = np.sum(S_s)/(len(S_s))
        
        X -= λ * Z
        sigma.append(row)
        phi.append(phi_row)
        S.append(S_row)

        if not first_iteration and Delta_D < e:
            print(f"Converged at iteration {i + 1}")
            break

        first_iteration = False
        i += 1
        
    out = np.array(out)
    sigma = np.array(sigma)
    phi = np.array(phi)
    S = np.array(S)


    return out, sigma, phi, S, as_grid(σ)

