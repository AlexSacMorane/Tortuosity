def first_lame_coefficient(μ, ν):
    return 2.0 * μ * ν / (1.0 - 2.0 * ν)


def bulk_modulus(μ, ν, dim):
    λ = first_lame_coefficient(μ, ν)
    return λ + 2.0 * μ / dim

# Linear elasticity
def C_ε(C, ε):
    ε = np.asarray(ε)
    d = C.dim
    μ = C.g
    λ = first_lame_coefficient(C.g, C.nu)
    tr_ε = np.sum(ε[..., :d], axis=-1, keepdims=1)
    σ = 2 * μ * ε
    σ[..., :d] += λ * tr_ε
    return σ


class MyLinearOperator(LinearOperator):
    def __init__(self, op):
        self.op = op
        self.ishape = op.ishape
        self.oshape = op.oshape
        self.shape = (np.product(op.oshape), np.product(op.ishape))
        self.dtype = np.dtype(np.float64)

    def _matvec(self, x):
        x = x.reshape(self.op.ishape)
        return np.asarray(self.op.apply(x)).ravel()

    def _rmatvec(self, x):
        #NOTE: assume symmetric operator
        x = x.reshape(self.op.ishape)
        return np.asarray(self.op.apply(x)).ravel()

