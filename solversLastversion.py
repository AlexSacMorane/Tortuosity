def reference_material(κ, μ, dim, operation):
    if operation == "arithmetic":
        κ0 = 0.5 * (np.max(κ) + np.min(κ))
        μ0 = 0.5 * (np.max(μ) + np.min(μ))
    elif operation == "geometric":
        κ0 = np.sqrt(np.max(κ) * np.min(κ))
        μ0 = np.sqrt(np.max(μ) * np.min(μ))
    elif operation == "maximum":
        α = 1.0 + 1.0e-2
        κ0 = np.max(κ) * α
        μ0 = np.max(μ) * α
    elif operation == "minimum":
        α = 1.0 - 1.0e-2
        κ0 = np.min(κ) * α
        μ0 = np.min(μ) * α
    else:
        raise ValueError(f"Invalid operation: {operation}")
    ν0 = material.poisson_from_bulk_and_shear_moduli(κ0, μ0, dim)
    return material.create(μ0, ν0, dim)



def projection_residuals(X, Γ0):
    C0 = Γ0.green.mat
    print("caution : X has to be in grid format")
    X_D = Γ0.apply(C_ε(C0, X))
    X_S = X - X_D
    res_D = np.sqrt(np.sum(X_D * C_ε(C0, X_D)))
    res_S = np.sqrt(np.sum(X_S * C_ε(C0, X_S)))
    return res_D, res_S




def tensor_average(C_0, C_1, C_Reuss, average):
    if average == "Voigt":
        C_eff = C_0 + C_1
    elif average == "Reuss":
        C_eff = C_Reuss
    elif average == "VR_mean":
        C_eff = 1/2 * (C_Reuss + (C_0 + C_1))
    return C_eff


def moulinec_suquet(
    φ, κ, μ, ν, ε_macro, max_iter, average, green_op_name="willot2015", **kwargs
):
    """
    Moulinec-Suquet scheme
    """

    # ----- Reference material -----

    dim = φ.ndim
    κ0 = 0.5 * (np.max(κ) + np.min(κ))
    μ0 = 0.5 * (np.max(μ) + np.min(μ))
    C0 = reference_material(κ, μ, φ.ndim, "arithmetic")
    S0 = material.create(
        1 / (C0.g * 4),
        material.poisson_from_bulk_and_shear_moduli(
            1 / (C0.k * dim**2), 1 / (C0.g * 4), dim
        ),
        dim,
    )
    Γ0 = green_operator(C0, φ.shape, green_op_name=green_op_name)
    C_ref = local_operator_(φ, φ.ndim * κ0, 2 * μ0, "Reference")
    phi_norm = φ / 255
    κ_field_R = 1/((1-phi_norm)/κ[0] + (phi_norm)/κ[1])
    μ_field_R = 1/((1-phi_norm)/μ[0] + (phi_norm)/μ[1])

    a0 = (φ.ndim * κ[0] + 2 * μ[0])/(2 * φ.ndim * κ[0] * 2 * μ[0])
    a1 = (φ.ndim * κ[1] + 2 * μ[1])/(2 * φ.ndim * κ[1] * 2 * μ[1])
    b0 = -(φ.ndim * κ[0] - 2 * μ[0])/(2 * φ.ndim * κ[0] * 2 * μ[0])
    b1 = -(φ.ndim * κ[1] - 2 * μ[1])/(2 * φ.ndim * κ[1] * 2 * μ[1])
    c0 = 1/(2 * μ[0])
    c1 = 1/(2 * μ[1])
    sa = (1-phi_norm) * a0 + phi_norm * a1
    sb = (1-phi_norm) * b0 + phi_norm * b1
    c = 1/((1-phi_norm)  * c0 + phi_norm * c1)
    C_0 = local_operator_(φ, (φ.ndim * κ[0])*(1-phi_norm), (2 * μ[0])*(1-phi_norm), "Grayscale")
    C_1 = local_operator_(φ, (φ.ndim * κ[1])*(phi_norm), (2 * μ[1])*phi_norm, "Grayscale")

    C_Reuss = local_operator_inv(φ, sa ,sb, c)

    ΔC = tensor_average(C_0, C_1, C_Reuss, average) - C_ref

    Cmatrix = material.create(μ[0], ν[0], dim)
    Smatrix = material.create(
        1 / (Cmatrix.g * 4),
        material.poisson_from_bulk_and_shear_moduli(
            1 / (Cmatrix.k * dim**2), 1 / (Cmatrix.g * 4), dim
        ),
        dim,
    )

    vol = np.prod(φ.shape)

    def ref_norm(X):
        X_ = as_grid(X)
        return np.sqrt(np.sum(X_ * C_ε(C0, X_)))

    num_cols = 6
    out = np.zeros((max_iter, num_cols), dtype=np.float64)
    as_grid = lambda a: np.reshape(a, Γ0.oshape)
    as_vector = lambda a: a.ravel()

    def projection_on_D(X):
        return Γ0 @ C_ε(C0, as_grid(X)).ravel()

    # ----- Fields Initialization -----

    E_macro = np.zeros(Γ0.oshape)
    E_macro[...] = ε_macro
    E_norm = ref_norm(E_macro)
    E_macro = as_vector(E_macro)

    ε = E_macro
    X = -Γ0 @ ΔC @ E_macro
    with open("sigma11_iter.txt", "w") as f:
        f.write("")
    with open("sigma12_iter.txt", "w") as f:
        f.write("")

    λ = 0.0
    ε_old = ε.copy()

    for i in range(max_iter):

        if (i + 1) % 10 == 0:
            print(f"Moulinec-Suquet scheme, iteration #{i + 1}/{max_iter}", flush=True)

        σ = tensor_average(C_0, C_1, C_Reuss, average) @ ε

        # Corrected residual using C0=C_matrix, to compare with other algorithms
        # X = projection_on_D(-C_ε(S0, as_grid(σ)).ravel())
        X_corrected = projection_on_D(-C_ε(Smatrix, as_grid(σ)).ravel())
        residual = ref_norm(X_corrected) / E_norm

        # Xnorm = ref_norm(X) / E_norm
        energy = np.sum(σ * ε) / vol
        Delta_S = 0
        Delta_D = ref_norm(X) / ref_norm(C_ε(S0, as_grid(σ)))

        out[i, :] = (
            residual,
            energy,
            λ,
            ref_norm(ε - ε_old) / ref_norm(ε_old),
            Delta_D,
            Delta_S,
        )

        ε_old = ε.copy()
        σ_12 = np.sum(σ[2::3])*1e-6/(len(σ)/3)
        σ_11 = np.sum(σ[::3])*1e-6/(len(σ)/3)
        with open("sigma11_iter.txt", "a") as f:
            np.savetxt(f, [σ_11])
        with open("sigma12_iter.txt", "a") as f:
            np.savetxt(f, [σ_12])
        Z = X + Γ0 @ ΔC @ X
        ε += X
        X -= Z

    return out, as_grid(ε), as_grid(σ), ε, σ


def cg(φ, κ, μ, ν, ε_macro, max_iter, mu0=None, green_op_name="willot2015", **kwargs):
    """
    Conjugate gradient algorithm, by Zeman et al.
    """

    from scipy.sparse.linalg._interface import IdentityOperator

    ν0 = ν[0]  # reference material is set to matrix
    μ0 = μ[0]

    if mu0 is not None:
        μ0 = mu0

    dim = φ.ndim
    C0 = material.create(μ0, ν0, φ.ndim)
    # S0 = material.create(1/(C0.g*4) , material.poisson_from_bulk_and_shear_moduli(1/(C0.k*dim**2), 1/(C0.g*4), dim), dim)
    Cmatrix = material.create(μ[0], ν[0], dim)
    Smatrix = material.create(
        1 / (Cmatrix.g * 4),
        material.poisson_from_bulk_and_shear_moduli(
            1 / (Cmatrix.k * dim**2), 1 / (Cmatrix.g * 4), dim
        ),
        dim,
    )

    Γ0 = green_operator(C0, φ.shape, green_op_name=green_op_name)
    C = local_operator(φ, φ.ndim * κ, 2 * μ)
    ΔC = local_operator(φ, φ.ndim * (κ - C0.k), 2 * (μ - C0.g))

    as_grid = lambda a: np.reshape(a, Γ0.oshape)
    as_vector = lambda a: a.ravel()

    def ref_norm(X):
        X_ = as_grid(X)
        return np.sqrt(np.sum(X_ * C_ε(C0, X_)))

    vol = np.prod(φ.shape)

    # ----- Fields Initialization -----

    E_macro = np.zeros(Γ0.oshape)
    E_macro[...] = ε_macro
    E_norm = ref_norm(E_macro)
    E_macro = as_vector(E_macro)

    global ε_old
    ε_old = np.zeros_like(E_macro)

    op = IdentityOperator(shape=Γ0.shape, dtype=Γ0.dtype) + Γ0 @ ΔC

    out = []

    i = itertools.count()

    def projection_on_D(X):
        return Γ0 @ C_ε(C0, as_grid(X)).ravel()

    def callback(ε, i=i):
        print(f"Conjugate gradient, iteration #{next(i) + 1}/{max_iter}", flush=True)

        global ε_old

        σ = C @ ε
        σ_m = C_ε(Smatrix, as_grid(σ))
        XD = -projection_on_D(σ_m)
        X_corrected = XD

        residual = ref_norm(X_corrected) / E_norm
        energy = np.sum(ε * σ) / vol
        Delta_S = 0
        Delta_D = ref_norm(XD) / ref_norm(σ_m)

        out.append(
            (
                residual,
                energy,
                0,  # no lambda for cg
                ref_norm(ε - ε_old) / ref_norm(ε_old),
                Delta_D,
                Delta_S,
            )
        )
        ε_old = ε.copy()

    ssl.cg(
        op, E_macro, x0=E_macro, M=None, maxiter=max_iter, callback=callback, tol=1e-16
    )

    return np.asarray(out)


def cg_DeltaJ(
    φ, κ, μ, ν, ε_macro, max_iter, mu0=None, green_op_name="willot2015", **kwargs
):
    """
    Conjugate gradient algorithm on tZ:Z
    """

    from scipy.sparse.linalg._interface import IdentityOperator

    ν0 = ν[0]  # reference material is set to matrix
    μ0 = μ[0]

    if mu0 is not None:
        μ0 = mu0

    dim = φ.ndim
    C0 = material.create(μ0, ν0, φ.ndim)
    # S0 = material.create(1/(C0.g*4) , material.poisson_from_bulk_and_shear_moduli(1/(C0.k*dim**2), 1/(C0.g*4), dim), dim)
    Γ0 = green_operator(C0, φ.shape, green_op_name=green_op_name)
    # C = local_operator(φ, φ.ndim * κ, 2 * μ)

    κ_0 = np.ones(3) * C0.k  # reference material is the same in the 3 phases
    μ_0 = np.ones(3) * C0.g
    C_0 = local_operator(φ, φ.ndim * κ_0, 2 * μ_0)

    as_grid = lambda a: np.reshape(a, Γ0.oshape)
    as_vector = lambda a: a.ravel()

    def ref_norm(X):
        X_ = as_grid(X)
        return np.sqrt(np.sum(X_ * C_ε(C0, X_)))

    def alpha_tensor(C0, κ, μ, φ):
        ak = 2 * C0.k / (κ + C0.k)
        ak[μ == np.inf] = 0
        ag = 2 * C0.g / (μ + C0.g)
        ag[μ == np.inf] = 0
        α = local_operator(φ, ak, ag)
        return α

    α = alpha_tensor(C0, κ, μ, φ)

    vol = np.prod(φ.shape)

    # ----- Fields Initialization -----

    E_macro = np.zeros(Γ0.oshape)
    E_macro[...] = ε_macro
    E_norm = ref_norm(E_macro)
    E_macro = as_vector(E_macro)

    global ε_old
    ε_old = np.zeros_like(E_macro)

    Id = IdentityOperator(shape=Γ0.shape, dtype=Γ0.dtype)
    projection_on_D = Γ0 @ C_0
    op = α @ α + (4 * Id - 2 * α) @ projection_on_D - 2 * projection_on_D @ α

    out = []

    i = itertools.count()

    def projection_on_D(X):
        return Γ0 @ C_ε(C0, as_grid(X)).ravel()

    def projection_on_S(X):
        return X - projection_on_D(X)

    def callback(ε_star, i=i):
        print(f"Conjugate gradient, iteration #{next(i) + 1}/{max_iter}", flush=True)

        global ε_old

        ε = α @ ε_star
        σ_H = (2 * Id - α) @ ε_star
        σ = C_0 @ σ_H
        XD = -projection_on_D(σ_H)
        XS = projection_on_S(E_macro - ε)
        X = XD + XS

        Xnorm = ref_norm(X) / E_norm
        energy = np.sum(ε * σ) / vol
        Delta_S = ref_norm(XS) / ref_norm(E_macro - ε)
        Delta_D = ref_norm(XD) / ref_norm(σ_H)

        out.append(
            (
                Xnorm,
                energy,
                0,  # no lambda for cg
                ref_norm(ε - ε_old) / ref_norm(ε_old),
                Delta_D,
                Delta_S,
            )
        )
        ε_old = ε.copy()

    ssl.cg(
        op,
        α @ E_macro,
        x0=E_macro,
        M=None,
        maxiter=max_iter,
        callback=callback,
        tol=1e-16,
    )

    return np.asarray(out)


