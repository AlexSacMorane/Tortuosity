def adaptive_eyre_milton(
    φ, κ, μ, ν, ε_macro, average, e, mu0=None, green_op_name="willot2015", **kwargs
):
    """
    Adaptive Eyre-Milton scheme & more

    """
    dim = φ.ndim
    κ0 = 0.5 * (np.max(κ) + np.min(κ))
    μ0 = 0.5 * (np.max(μ) + np.min(μ))
    # ----- Reference material -----

    if mu0 is not None:
        μ0 = mu0

    phi_norm = φ / 255
    dim = φ.ndim
    C0 = reference_material(κ, μ, φ.ndim, "arithmetic")
    κ_field_V =κ[0] * (1-phi_norm) + κ[1] * (phi_norm)
    μ_field_V = μ[0] * (1-phi_norm) + μ[1] * (phi_norm)
    κ_field_R = 1/((1-phi_norm)/( κ[0]) + (phi_norm)/( κ[1]))
    μ_field_R = 1/((1-phi_norm)/μ[0] + (phi_norm)/μ[1])
    def alpha_tensor(C0, κ_V, μ_V, κ_R, μ_R, average, φ):

        if average == "Voigt":
            ak = 2 * C0.k / (κ_V  + C0.k)
            ag = 2 * C0.g / (μ_V + C0.g)
        if average == "Reuss":
            ak = 2 * C0.k / (κ_R  + C0.k)
