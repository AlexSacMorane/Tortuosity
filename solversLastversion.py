def local_operator(φ, sph, dev):
    """
    Create the operator x ↦ y, where

    y[i, j, k] = T[i, j, k] @ x[i, j, k]

    and

    T[i, j, k] = sph[φ[i, j, k]] * J + dev[φ[i, j, k]] * K
    """
    loc = [operators.isotropic_4(x, y, dim=φ.ndim) for x, y in zip(sph, dev)]
    print(loc)
    op = operators.block_diagonal_operator(np.array(loc)[φ])
    return MyLinearOperator(op)

